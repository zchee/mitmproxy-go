// Command genlayout derives PF offsets from pinned header declarations using clang.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func declaration(header, name string) (string, error) {
	re := regexp.MustCompile(`(?ms)^` + regexp.QuoteMeta(name) + ` \{.*?^\};`)
	decl := re.FindString(header)
	if decl == "" {
		return "", fmt.Errorf("missing declaration %s", name)
	}
	// pf_addr embeds member aliases; only the actual C fields determine its layout.
	decl = regexp.MustCompile(`(?m)^#define[^\n]*\n`).ReplaceAllString(decl, "")
	return decl, nil
}

func generate() error {
	if len(os.Args) != 3 {
		return fmt.Errorf("usage: genlayout HEADER_DIRECTORY OUTPUT_GO")
	}
	var out bytes.Buffer
	out.WriteString("// Copyright 2026 The mitmproxy-go Authors.\n// SPDX-License-Identifier: MIT\n\n// Code generated by go run ./internal/platform/genlayout; DO NOT EDIT.\n\npackage platform\n\n")
	tests := map[string]struct{ prefix, target, revision string }{
		"darwin":  {"xnu", "arm64-apple-macos", "xnu-12377.1.9"},
		"freebsd": {"freebsd", "x86_64-unknown-freebsd", "release/14.3.0"},
	}
	// Stable output independent of map iteration order.
	for _, osName := range []string{"darwin", "freebsd"} {
		test := tests[osName]
		header, err := os.ReadFile(filepath.Join(os.Args[1], test.prefix+"-pfvar.h"))
		if err != nil {
			return err
		}
		addrHeader := header
		if osName == "freebsd" {
			addrHeader, err = os.ReadFile(filepath.Join(os.Args[1], "freebsd-pf.h"))
			if err != nil {
				return err
			}
		}
		addr, err := declaration(string(addrHeader), "struct pf_addr")
		if err != nil {
			return err
		}
		nat, err := declaration(string(header), "struct pfioc_natlook")
		if err != nil {
			return err
		}
		var transport string
		if osName == "darwin" {
			transport, err = declaration(string(header), "union pf_state_xport")
			if err != nil {
				return err
			}
		}
		ioc, err := os.ReadFile(filepath.Join(os.Args[1], test.prefix+"-ioccom.h"))
		if err != nil {
			return err
		}
		// Include only ioctl macros, including their continued lines, from the pinned header.
		iocText := regexp.MustCompile(`(?s)/\*.*?\*/`).ReplaceAllString(string(ioc), "")
		macros := regexp.MustCompile(`(?m)^#define[^\n]*`).FindAllString(strings.ReplaceAll(iocText, "\\\n", " "), -1)
		c := "typedef unsigned char u_int8_t; typedef unsigned short u_int16_t; typedef unsigned int u_int32_t; typedef unsigned int __uint32_t; typedef unsigned char sa_family_t;\nstruct in_addr { u_int32_t s_addr; }; struct in6_addr { u_int8_t s6_addr[16]; };\n" + addr + "\n" + transport + "\n" + nat + "\n" + strings.Join(macros, "\n") + "\nenum { generated_ioctl = _IOWR('D', 23, struct pfioc_natlook) };\n"
		cmd := exec.Command("clang", "-target", test.target, "-x", "c", "-Xclang", "-fdump-record-layouts-complete", "-Xclang", "-ast-dump", "-fsyntax-only", "-") //nolint:gosec // Offline generator only; fixed argv and target table, never traffic or header input.
		cmd.Stdin = strings.NewReader(c)
		dump, err := cmd.CombinedOutput()
		if err != nil {
			return fmt.Errorf("clang %s: %w\n%s", osName, err, dump)
		}
		text := string(dump)
		_, record, found := strings.Cut(text, "| struct pfioc_natlook\n")
		if !found {
			return fmt.Errorf("missing clang record for %s", osName)
		}
		sizeMatch := regexp.MustCompile(`\[sizeof=(\d+), align=(\d+)\]`).FindStringSubmatch(record)
		if len(sizeMatch) != 3 {
			return fmt.Errorf("missing clang size for %s", osName)
		}
		ioctlMatch := regexp.MustCompile(`value: Int (\d+)`).FindStringSubmatch(text)
		if len(ioctlMatch) != 2 {
			return fmt.Errorf("missing clang ioctl for %s", osName)
		}
		ioctlValue, err := strconv.ParseUint(ioctlMatch[1], 10, 32)
		if err != nil {
			return err
		}
		fmt.Fprintf(&out, "// %s PF layout, derived by clang for %s.\nvar %sPFLayout = pfLayout{\nsize: %s, alignment: %s, ioctl: %#x,\n", test.revision, test.target, osName, sizeMatch[1], sizeMatch[2], ioctlValue)
		for _, pair := range [][2]string{{"source", "saddr"}, {"destination", "daddr"}, {"result", "rdaddr"}, {"sourcePort", "sport"}, {"destinationPort", "dport"}, {"resultPort", "rdport"}, {"family", "af"}, {"protocol", "proto"}, {"direction", "direction"}} {
			name := pair[1]
			if osName == "darwin" {
				name = strings.Replace(name, "port", "xport", 1)
			}
			m := regexp.MustCompile(`(?m)^\s*(\d+) \|   (?:struct|union|u_int16_t|u_int8_t|sa_family_t)[^\n]*\b` + name + `$`).FindStringSubmatch(record)
			if len(m) != 2 {
				return fmt.Errorf("missing clang offset for %s.%s", osName, name)
			}
			fmt.Fprintf(&out, "%s: %s,\n", pair[0], m[1])
		}
		out.WriteString("}\n\n")
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(os.Args[2], formatted, 0o644) //nolint:gosec // Generated Go source is intentionally readable, never secret.
}
