//go:build darwin || freebsd

package platform

import (
	"context"
	"fmt"
	"net"
	"net/netip"
	"runtime"
	"unsafe"

	"golang.org/x/sys/unix"

	"github.com/zchee/mitmproxy-go/connection"
)

var nativePFResolver = pfResolver{native: nativePFAddr, text: readPFState}

func originalAddr(ctx context.Context, conn *net.TCPConn) (connection.Address, error) {
	local, err := tcpAddress(conn.LocalAddr())
	if err != nil {
		return connection.Address{}, err
	}
	peer, err := tcpAddress(conn.RemoteAddr())
	if err != nil {
		return connection.Address{}, err
	}
	return nativePFResolver.lookup(ctx, local, peer)
}

func nativePFAddr(ctx context.Context, local, peer netip.AddrPort) (connection.Address, error) {
	layout := darwinPFLayout
	if runtime.GOOS == "freebsd" {
		layout = freebsdPFLayout
	}
	calls := pfCalls{
		family4: unix.AF_INET, family6: unix.AF_INET6,
		open: func() (int, error) {
			fd, err := unix.Open("/dev/pf", unix.O_RDONLY|unix.O_CLOEXEC, 0)
			if err != nil {
				return -1, fmt.Errorf("open /dev/pf: %w", err)
			}
			return fd, nil
		},
		close: unix.Close,
		ioctl: func(fd int, request uintptr, buf []byte) error {
			// Kernel copyin/copyout uses the generated byte layout; buf stays live
			// throughout the call, and this descriptor is owned by pfNatLook.
			_, _, errno := unix.Syscall(unix.SYS_IOCTL, uintptr(fd), request, uintptr(unsafe.Pointer(&buf[0]))) //nolint:gosec,staticcheck // Live generated copyin/copyout buffer and caller-owned PF fd; x/sys has no arbitrary-pointer ioctl wrapper without cgo.
			if errno != 0 {
				return fmt.Errorf("DIOCNATLOOK: %w", errno)
			}
			return nil
		},
	}
	return pfNatLook(ctx, local, peer, layout, calls)
}
